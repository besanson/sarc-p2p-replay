"""DECISIONS.md D-F-1, external reproduction attempt 1 (issue #1), from results/reproduction/attempt-1.json,
with the author's reading of each difference. Nothing is typed.

Usage: python scripts/d_f_1.py --date YYYY-MM-DD
"""

from __future__ import annotations

import argparse
import json
import platform
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECISIONS = ROOT / "DECISIONS.md"
HEADING = "## D-F-1 "


def render(date: str) -> str:
    a = json.loads((ROOT / "results" / "reproduction" / "attempt-1.json").read_text(encoding="utf-8"))
    e, s, t = a["environment"], a["supplemental_comparison"], a["timeline_timestamps"]
    diffs = "\n".join(f"| `{d['file']}` | {d['differing_values']:,} | "
                      f"{'n/a' if d['max_abs_difference'] is None else repr(d['max_abs_difference'])} | {d['kind']} |"
                      for d in a["json_differences"])
    gates = ", ".join(f"{k} {v}" for k, v in a["gates"].items())
    tb = " -> ".join(f"`{f['file']}` {f['function']}" for f in a["reproduce_traceback"])
    data = "; ".join(f"`{d['file']}` {d['bytes']:,} bytes" for d in a["data_as_verified"])
    fd = a["first_download"]
    return f"""{HEADING}External reproduction attempt 1 (issue #{a['issue']}) ({date})

**The record, as found** (`{a['body']}`, the issue body unedited, SHA-256 `{a['body_sha256']}`;
`results/reproduction/attempt-{a['attempt']}.json`, every figure parsed from it by
`scripts/reproduction_attempts.py`). Reproducer: {a['reproducer']} (issue opened as `{a['opened_by']}`;
the report says an AI assistant helped run the commands and read the output). Release {e['release']},
commit `{e['commit'][:7]}`; {e['operating_system']}; Python {e['python']}; git {e['git']}; pandoc
{e['pandoc'].split(',')[0]}; TeX engine {e['tex_engine']}. Dates as reported: {a['dates']['initial_run_and_dataset_verification']}.

- Data: the first download of `{fd['file']}` had SHA-256 `{fd['sha256_got'][:16]}...`, not the registered
  `{fd['sha256_registered'][:16]}...`; `make bootstrap` deleted it, and one retry passed. Verified after the
  retry: {data}, each at its registered SHA-256.
- `make test`: {a['tests']['passed']} passed, {a['tests']['failed']} failed (`{a['tests']['failing_test']}`): the
  {t['differing_fields']} git timestamps of `results/e4/timeline.json` came out as `{t['regenerated_form']}` where the
  committed file has `{t['committed_form']}`.
- `make gates`: {gates}. G9 and `make reproduce` stopped on `{a['reproduce_exception']}` in the optional PDF
  step ({tb}): the engine was Tectonic, which writes no `main.log` where the script read one. No report
  was written.
- The reproducer's supplemental hash comparison of the files `make reproduce` had regenerated:
  {s['matched']} of {s['compared']} byte-identical, {s['differed']} differing: {len(s['differing_other_files'])} JSON files
  ({', '.join(f'`{x}`' for x in s['differing_other_files'])}) and the {len(s['differing_figure_files'])} figure files.
  The paper text, its TeX and the README were byte-identical. Parsed comparison of the result JSON:

| file | differing values | maximum absolute difference | kind |
|---|---:|---|---|
{diffs}

The reproducer asked that the status stay pending, not be described as a successful reproduction.

**The author's reading.**

- The numeric differences are floating-point last digits across architectures: {platform.machine()} Linux at the
  builder, {e['architecture']} macOS at the reproducer. The largest is {a['max_abs_numeric_difference']!r}. No
  reported number changed: the paper text and its TeX regenerated byte-identically, and they carry every
  reported number. `paper/filled-template.json` records the raw values beside the text and differs for the
  same reason.
- Figure bytes are machine-dependent (font embedding in SVG and PDF), not a difference in what is plotted.
- The timestamp form `Z` against `+00:00` comes from Apple Git; the instants are equal.
- The PDF step is optional and was unguarded: an engine other than pdflatex (Tectonic) writes no
  `main.log` there, and the exception stopped the run before its report.
- The first download's mismatch was transient: the retry, with the same URL and registered hash, passed.

**Conclusion.** The claim "byte-identical across machines" was too strong. It becomes: byte-identical on
one machine, and equal within tolerance across machines, with the paper text, its TeX and the README
byte-identical everywhere. The tooling is corrected in 1.0.1 (tolerance comparison beside the byte
comparison, timestamp normalisation, a guarded PDF step, the gate report kept out of the checkout, a
fetch retry), and the attempt is re-run on it. FINAL-AUDIT item 11 stays open.
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="d_f_1")
    parser.add_argument("--date", required=True)
    args = parser.parse_args(argv)
    entry = render(args.date)
    text = DECISIONS.read_text(encoding="utf-8")
    if HEADING in text:
        head, rest = text.split(HEADING, 1)
        tail = re.search(r"\n## ", rest)
        text = head + entry + ("\n" + rest[tail.start() + 1:] if tail else "")
    else:
        text = text.rstrip("\n") + "\n\n" + entry
    DECISIONS.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
